/** When no alias matches, guess the kind from the name so the leaderboard can still be filtered by type. */
export function guessKind(normalised: string): SponsorKind {
  if (/hospital|university|universit|medical cent|cancer cent|institut|college|clinic|health system|foundation trust|nhs|school of medicine|academ/.test(normalised)) return "institution";
  if (/group|consortium|network|cooperative|collaborative|study|trials unit|intergroup/.test(normalised)) return "cooperative-group";
  if (/ministry|national|government|agency|council|charity|society|foundation/.test(normalised)) return "government";
  if (/pharma|therapeutic|bio|oncology|medicine|labs?\b|sciences?|health|genetics|diagnostics|ag\b|sa\b|inc\b|ltd\b/.test(normalised)) return "company";
  return "other";
}

/** Lower-case, strip punctuation and generic corporate suffixes. */
export function normaliseSponsor(name: string): string {
  return name
    .toLowerCase()
    .replace(/[.,]/g, "")
    .replace(/\b(inc|llc|ltd|limited|corp|corporation|plc|ag|sa|nv|gmbh|kk|holdings?)\b/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/** Resolve a sponsor string to a target; returns the raw name as an "other" target when nothing matches. */
export function resolveSponsor(name: string): SponsorTarget & { matched: boolean } {
  const n = normaliseSponsor(name);
  for (const [re, t] of SPONSOR_PATTERNS) if (re.test(n)) return { ...t, matched: true };
  return { label: name.trim(), kind: guessKind(n), matched: false };
}
